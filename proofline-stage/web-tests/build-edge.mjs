import {readFile,writeFile,mkdir} from 'node:fs/promises';
const read=name=>readFile(new URL('../web/'+name,import.meta.url),'utf8');
const html=(await read('index.html'))
 .replace('<link rel="stylesheet" href="/styles.css">',`<style nonce="__NONCE__">${await read('styles.css')}</style>`)
 .replace('<script src="/workbench.js" defer></script>',`<script nonce="__NONCE__">${await read('workbench.js')}</script>`);
const dir=new URL('../supabase/proofline-staging-review-workbench/',import.meta.url);
await mkdir(dir,{recursive:true});
const handler=await readFile(new URL('edge-handler.txt',import.meta.url),'utf8');
await writeFile(new URL('index.ts',dir),'// Generated by web-tests/build-edge.mjs; edit web/ and regenerate.\nconst template='+JSON.stringify(html)+';\n'+handler);
